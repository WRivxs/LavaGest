-- -----------------------------------------------------------------------------
-- 7. TRIGGERS AUTOMATIZADOS
-- -----------------------------------------------------------------------------

-- Trigger 1: Auto-cálculo de comisión y formato de placa
CREATE OR REPLACE FUNCTION fn_calculate_wash_payment()
RETURNS TRIGGER AS $$
BEGIN
    -- Si el worker_payment viene nulo o en 0 pero hay un porcentaje, se calcula automáticamente
    IF NEW.worker_payment IS NULL OR (NEW.worker_payment = 0 AND NEW.price > 0) THEN
        NEW.worker_payment := ROUND(NEW.price * (NEW.commission_pct / 100.0), 2);
    END IF;
    
    -- Asegurar que la placa siempre quede en mayúsculas y sin espacios laterales
    NEW.plate := UPPER(TRIM(NEW.plate));
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_before_insert_wash
BEFORE INSERT OR UPDATE ON washes
FOR EACH ROW
EXECUTE FUNCTION fn_calculate_wash_payment();

-- Trigger 2: Marcar lavados como liquidados cuando se vinculan a un pago
CREATE OR REPLACE FUNCTION fn_sync_wash_payout_status()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.payout_id IS NOT NULL THEN
        NEW.payout_status := 'Liquidado';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sync_wash_payout
BEFORE INSERT OR UPDATE OF payout_id ON washes
FOR EACH ROW
EXECUTE FUNCTION fn_sync_wash_payout_status();

