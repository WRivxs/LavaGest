-- 8. VISTAS ANALÍTICAS Y REPORTES DE INGRESOS
-- -----------------------------------------------------------------------------

-- Vista 1: Detalle operativo de lavados (Para la tabla principal del Dashboard)
CREATE OR REPLACE VIEW v_washes_detailed AS
SELECT 
    w.id,
    w.wash_date,
    TO_CHAR(w.wash_time, 'HH24:MI') AS wash_time_formatted,
    w.plate,
    w.vehicle_type,
    COALESCE(w.vehicle_model, 'Sin especificar') AS vehicle_model,
    w.worker_id,
    k.name AS worker_name,
    k.bay AS worker_bay,
    w.price,
    w.worker_payment,
    w.profit,
    w.payout_status,
    w.payout_id,
    ROUND((w.profit / NULLIF(w.price, 0)) * 100, 1) AS profit_margin_pct,
    w.created_at
FROM washes w
INNER JOIN workers k ON w.worker_id = k.id
ORDER BY w.wash_date DESC, w.wash_time DESC;

-- Vista 2: Rendimiento general de trabajadores y acumulados históricos
CREATE OR REPLACE VIEW v_worker_performance AS
SELECT 
    k.id AS worker_id,
    k.name AS worker_name,
    k.bay,
    k.shift,
    k.active,
    COUNT(w.id) AS total_washes,
    COALESCE(SUM(w.price), 0.00) AS total_generated,          -- Total cobrado en sus lavados
    COALESCE(SUM(w.worker_payment), 0.00) AS total_commission, -- Comisión acumulada histórica
    COALESCE(SUM(w.profit), 0.00) AS business_profit,          -- Ganancia neta aportada
    ROUND(COALESCE(AVG(w.price), 0.00), 2) AS avg_ticket
FROM workers k
LEFT JOIN washes w ON k.id = w.worker_id
GROUP BY k.id, k.name, k.bay, k.shift, k.active
ORDER BY total_washes DESC, total_generated DESC;

-- Vista 3: MÓDULO DE NÓMINA - Comisiones pendientes por pagar a cada trabajador
CREATE OR REPLACE VIEW v_worker_pending_payouts AS
SELECT 
    k.id AS worker_id,
    k.name AS worker_name,
    k.bay,
    COUNT(w.id) AS pending_washes,
    COALESCE(SUM(w.worker_payment), 0.00) AS pending_amount_to_pay, -- Lo que se le debe pagar hoy
    COALESCE(SUM(w.price), 0.00) AS pending_revenue_generated
FROM workers k
LEFT JOIN washes w ON k.id = w.worker_id AND w.payout_status = 'Pendiente'
WHERE k.active = true
GROUP BY k.id, k.name, k.bay
ORDER BY pending_amount_to_pay DESC;

-- Vista 4: REPORTE DIARIO DE INGRESOS (Agrupado por día con desglose financiero)
CREATE OR REPLACE VIEW v_income_report_daily AS
SELECT 
    w.wash_date AS report_date,
    COUNT(w.id) AS total_washes,
    
    -- Desglose por tipo de vehículo
    COUNT(CASE WHEN w.vehicle_type = 'Carro' THEN 1 END) AS cars_count,
    COUNT(CASE WHEN w.vehicle_type = 'Moto' THEN 1 END) AS motos_count,
    
    -- Ingresos por tipo
    COALESCE(SUM(CASE WHEN w.vehicle_type = 'Carro' THEN w.price ELSE 0 END), 0.00) AS income_cars,
    COALESCE(SUM(CASE WHEN w.vehicle_type = 'Moto' THEN w.price ELSE 0 END), 0.00) AS income_motos,
    
    -- Consolidado financiero
    COALESCE(SUM(w.price), 0.00) AS gross_income,                    -- Ingresos Brutos Totales
    COALESCE(SUM(w.worker_payment), 0.00) AS total_commissions,      -- Comisiones correspondientes
    COALESCE(SUM(w.profit), 0.00) AS net_profit,                     -- Ganancia Neta del Negocio
    
    -- Pagos efectivamente desembolsados de caja ese día
    COALESCE(p.payouts_disbursed, 0.00) AS cash_payouts_disbursed,
    
    -- Ticket promedio
    ROUND(COALESCE(AVG(w.price), 0.00), 2) AS avg_ticket_price,
    ROUND(
        (COALESCE(SUM(w.profit), 0.00) / NULLIF(SUM(w.price), 0)) * 100, 1
    ) AS profit_margin_pct
FROM washes w
LEFT JOIN (
    SELECT payment_date, SUM(amount) AS payouts_disbursed
    FROM worker_payouts
    WHERE status = 'Pagado'
    GROUP BY payment_date
) p ON w.wash_date = p.payment_date
GROUP BY w.wash_date, p.payouts_disbursed
ORDER BY w.wash_date DESC;

-- Vista 5: REPORTE MENSUAL DE INGRESOS (Consolidado mes a mes)
CREATE OR REPLACE VIEW v_income_report_monthly AS
SELECT 
    TO_CHAR(w.wash_date, 'YYYY-MM') AS year_month,
    COUNT(w.id) AS total_washes,
    COALESCE(SUM(w.price), 0.00) AS total_gross_income,
    COALESCE(SUM(w.worker_payment), 0.00) AS total_commissions,
    COALESCE(SUM(w.profit), 0.00) AS total_net_profit,
    ROUND(COALESCE(AVG(w.price), 0.00), 2) AS avg_ticket,
    COUNT(DISTINCT w.wash_date) AS operating_days,
    ROUND(COALESCE(SUM(w.price) / NULLIF(COUNT(DISTINCT w.wash_date), 0), 0.00), 2) AS avg_daily_income
FROM washes w
GROUP BY TO_CHAR(w.wash_date, 'YYYY-MM')
ORDER BY year_month DESC;

-- Vista 6: Resumen financiero del día actual (Para los KPIs del Dashboard Principal)
CREATE OR REPLACE VIEW v_daily_summary AS
SELECT 
    CURRENT_DATE AS summary_date,
    COUNT(w.id) AS washes_today,
    COALESCE(SUM(w.price), 0.00) AS total_income,
    COALESCE(SUM(w.worker_payment), 0.00) AS total_worker_payments,
    COALESCE(SUM(w.profit), 0.00) AS total_profit,
    
    -- Conteo por tipo
    COUNT(CASE WHEN w.vehicle_type = 'Carro' THEN 1 END) AS cars_count,
    COUNT(CASE WHEN w.vehicle_type = 'Moto' THEN 1 END) AS motos_count,
    
    -- Margen y tickets
    ROUND(COALESCE(AVG(w.price), 0.00), 2) AS avg_ticket,
    ROUND(COALESCE(AVG(w.profit), 0.00), 2) AS avg_profit,
    
    -- Porcentajes de distribución
    ROUND(
        (COUNT(CASE WHEN w.vehicle_type = 'Carro' THEN 1 END)::numeric / 
        NULLIF(COUNT(w.id), 0)) * 100, 1
    ) AS cars_percentage,
    ROUND(
        (COUNT(CASE WHEN w.vehicle_type = 'Moto' THEN 1 END)::numeric / 
        NULLIF(COUNT(w.id), 0)) * 100, 1
    ) AS motos_percentage
FROM washes w
WHERE w.wash_date = CURRENT_DATE;

-- Vista 7: Tendencia de ingresos de los últimos 7 días (Para la gráfica de barras)
CREATE OR REPLACE VIEW v_weekly_trend AS
SELECT 
    d.day_date,
    TO_CHAR(d.day_date, 'Dy') AS day_name,
    COUNT(w.id) AS washes_count,
    COALESCE(SUM(w.price), 0.00) AS total_income,
    COALESCE(SUM(w.profit), 0.00) AS total_profit
FROM (
    SELECT CURRENT_DATE - i AS day_date
    FROM generate_series(6, 0, -1) AS i
) d
LEFT JOIN washes w ON w.wash_date = d.day_date
GROUP BY d.day_date
ORDER BY d.day_date ASC;

-- -----------------------------------------------------------------------------
-- 9. FUNCIÓN ALMACENADA: REPORTE FINANCIERO POR RANGO DE FECHAS
-- -----------------------------------------------------------------------------
-- Permite consultar el balance financiero entre cualquier rango (Hoy, Ayer, Esta semana, Mes, Personalizado)
CREATE OR REPLACE FUNCTION fn_financial_report(p_start_date DATE, p_end_date DATE)
RETURNS TABLE (
    total_washes BIGINT,
    total_cars BIGINT,
    total_motos BIGINT,
    gross_income NUMERIC,
    worker_commissions NUMERIC,
    net_profit NUMERIC,
    profit_margin_pct NUMERIC,
    avg_ticket NUMERIC
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        COUNT(w.id) AS total_washes,
        COUNT(CASE WHEN w.vehicle_type = 'Carro' THEN 1 END) AS total_cars,
        COUNT(CASE WHEN w.vehicle_type = 'Moto' THEN 1 END) AS total_motos,
        COALESCE(SUM(w.price), 0.00) AS gross_income,
        COALESCE(SUM(w.worker_payment), 0.00) AS worker_commissions,
        COALESCE(SUM(w.profit), 0.00) AS net_profit,
        ROUND((COALESCE(SUM(w.profit), 0.00) / NULLIF(SUM(w.price), 0)) * 100, 1) AS profit_margin_pct,
        ROUND(COALESCE(AVG(w.price), 0.00), 2) AS avg_ticket
    FROM washes w
    WHERE w.wash_date BETWEEN p_start_date AND p_end_date;
END;
$$ LANGUAGE plpgsql;

