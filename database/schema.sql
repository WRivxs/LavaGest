-- -----------------------------------------------------------------------------
-- 2. TABLA DE TRABAJADORES (Operadores del Lavadero)
-- -----------------------------------------------------------------------------
CREATE TABLE workers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT,
    bay TEXT DEFAULT 'Bahía 1',               -- Ej: Bahía 1, Bahía 2, Bahía 3
    shift TEXT DEFAULT 'Turno Completo',       -- Ej: Turno Completo, Medio Turno
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE workers IS 'Registro de lavadores y operadores de bahía.';

-- -----------------------------------------------------------------------------
-- 3. TABLA DE TARIFAS Y SERVICIOS BASE (Carros y Motos)
-- -----------------------------------------------------------------------------
CREATE TABLE service_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_type TEXT NOT NULL UNIQUE CHECK (vehicle_type IN ('Carro', 'Moto')),
    service_name TEXT NOT NULL,               -- Ej: "Lavado General + Aspirado"
    default_price NUMERIC(12, 2) NOT NULL CHECK (default_price >= 0),
    commission_pct NUMERIC(5, 2) NOT NULL DEFAULT 40.00 CHECK (commission_pct >= 0 AND commission_pct <= 100),
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE service_rates IS 'Configuración de precios sugeridos y porcentaje de comisión para operadores.';

-- -----------------------------------------------------------------------------
-- 4. TABLA DE PAGOS Y LIQUIDACIÓN A TRABAJADORES (Nómina / Egresos de Caja)
-- -----------------------------------------------------------------------------
CREATE TABLE worker_payouts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id BIGINT NOT NULL REFERENCES workers(id) ON DELETE RESTRICT,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),             -- Monto total liquidado y entregado
    payment_method TEXT NOT NULL DEFAULT 'Efectivo' 
        CHECK (payment_method IN ('Efectivo', 'Nequi', 'Daviplata', 'Transferencia')),
    payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    payment_time TIME NOT NULL DEFAULT CURRENT_TIME,
    status TEXT NOT NULL DEFAULT 'Pagado' CHECK (status IN ('Pendiente', 'Pagado', 'Anulado')),
    notes TEXT,                                                   -- Ej: 'Liquidación jornada tarde 6 lavados'
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE worker_payouts IS 'Registro de liquidaciones de comisión y salidas de caja efectivas hacia los lavadores.';

-- -----------------------------------------------------------------------------
-- 5. TABLA PRINCIPAL DE LAVADOS (Registro Operativo y Financiero)
-- -----------------------------------------------------------------------------
CREATE TABLE washes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate TEXT NOT NULL,                                           -- Placa del vehículo (ej: ABC-492)
    vehicle_type TEXT NOT NULL CHECK (vehicle_type IN ('Carro', 'Moto')),
    vehicle_model TEXT,                                            -- Modelo y color (ej: 'Mazda 3 Blanco')
    worker_id BIGINT NOT NULL REFERENCES workers(id) ON DELETE RESTRICT,
    
    -- Finanzas por ticket
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),              -- Total cobrado al cliente (Ingreso)
    commission_pct NUMERIC(5, 2) NOT NULL DEFAULT 40.00 CHECK (commission_pct >= 0 AND commission_pct <= 100),
    worker_payment NUMERIC(12, 2) NOT NULL CHECK (worker_payment >= 0), -- Comisión que le corresponde al trabajador
    
    -- Ganancia calculada automáticamente de forma consistente y persistida
    profit NUMERIC(12, 2) GENERATED ALWAYS AS (price - worker_payment) STORED, -- Utilidad neta del negocio
    
    -- Control de liquidación de la comisión
    payout_id BIGINT REFERENCES worker_payouts(id) ON DELETE SET NULL, -- Si ya fue liquidado en un pago
    payout_status TEXT NOT NULL DEFAULT 'Pendiente' CHECK (payout_status IN ('Pendiente', 'Liquidado')),
    
    -- Tiempos y notas
    wash_date DATE NOT NULL DEFAULT CURRENT_DATE,
    wash_time TIME NOT NULL DEFAULT CURRENT_TIME,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    
    -- Validación de integridad financiera: el pago no puede ser mayor al precio cobrado
    CONSTRAINT worker_payment_not_above_price CHECK (worker_payment <= price)
);

COMMENT ON TABLE washes IS 'Registro transaccional de cada lavado con cálculo automático de comisiones, margen y estado de liquidación.';

-- -----------------------------------------------------------------------------
